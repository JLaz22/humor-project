create table if not exists public.generations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  prompt text not null check (char_length(prompt) between 3 and 280),
  style text not null check (style in ('deadpan', 'chaotic', 'wholesome')),
  generation_prompt text not null,
  content text not null check (char_length(content) between 1 and 500),
  model text not null,
  upvotes integer not null default 0 check (upvotes >= 0),
  downvotes integer not null default 0 check (downvotes >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  generation_id bigint not null references public.generations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  value smallint not null check (value in (-1, 1)),
  created_at timestamptz not null default now(),
  unique (generation_id, user_id)
);

create index if not exists generations_created_at_idx
on public.generations (created_at desc);

create index if not exists votes_user_id_idx
on public.votes (user_id);

create or replace function public.update_generation_vote_totals()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  if new.value = 1 then
    update public.generations
    set upvotes = upvotes + 1
    where id = new.generation_id;
  else
    update public.generations
    set downvotes = downvotes + 1
    where id = new.generation_id;
  end if;
  return new;
end;
$$;

drop trigger if exists on_vote_created on public.votes;
create trigger on_vote_created
  after insert on public.votes
  for each row execute procedure public.update_generation_vote_totals();

