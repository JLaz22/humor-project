drop policy if exists "Generations are publicly readable" on public.generations;
create policy "Generations are publicly readable"
on public.generations for select to anon, authenticated
using (true);

drop policy if exists "Users can create their own generations" on public.generations;
create policy "Users can create their own generations"
on public.generations for insert to authenticated
with check (
  (select auth.uid()) = user_id
  and upvotes = 0
  and downvotes = 0
);

drop policy if exists "Users can read their own votes" on public.votes;
create policy "Users can read their own votes"
on public.votes for select to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "Users can create their own votes" on public.votes;
create policy "Users can create their own votes"
on public.votes for insert to authenticated
with check ((select auth.uid()) = user_id);
